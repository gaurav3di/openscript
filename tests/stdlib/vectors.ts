/**
 * Reference vectors for the gate studies.
 *
 * Eighty bars, every price a whole number of cents, with a trend, a pullback, a
 * gap up, a flat stretch and a reversal in it. The expected values were
 * produced by the reference implementations in this project's sibling chart
 * package, not by the library under test, which is the only thing that makes a
 * comparison against them worth running.
 *
 * The Bollinger vectors are the exception: they come from a fresh window sum
 * written from the definition, because the sibling's simple mean carries a
 * running total and subtracts the bar that leaves the window. That arrangement
 * drifts, it is the less accurate of the two, and `compiled-program.md` section
 * 8.3 refuses it. The two disagree by at most about two parts in a quadrillion
 * on this fixture, which is a difference in the sibling's accumulation and not
 * in this library's arithmetic.
 *
 * `null` is a bar the reference has no value for. The supertrend vectors have
 * one extra `null`, at bar 9: the reference reports its own seed bar, and
 * `stdlib.md` section 4 declares the first value at bar `atrLen` instead, for
 * the reason `supertrend.ts` sets out. That one bar is the only place the two
 * disagree, and it is a disagreement about which bar exists rather than about a
 * number.
 *
 * Regenerating these is a deliberate act. If a change here makes a vector
 * change, the arithmetic changed, and that is the thing to explain.
 */
